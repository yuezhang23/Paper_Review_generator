"""
Plagiarism Service - Handles plagiarism detection functionality for the Plagiarism tab
"""

import re
import json
from typing import Optional, List, Dict, Any
from fastapi import HTTPException, APIRouter
from pydantic import BaseModel
from utils import get_ai_client, extract_paper_content

# Create router for plagiarism endpoints
router = APIRouter(prefix="/api", tags=["plagiarism"])


class PlagiarismCheckRequest(BaseModel):
    file_ids: Optional[List[str]] = None
    paper_url: Optional[str] = None
    paper_name: Optional[str] = None


async def check_string_matching(text: str) -> Dict[str, Any]:
    """Check for copy-paste plagiarism using string matching"""
    # Simple heuristic: check for common phrases that might indicate copying
    # In a real implementation, this would compare against a database of papers
    suspicious_phrases = [
        "as shown in", "it is well known that", "previous work has shown",
        "we propose a novel", "the main contribution", "experimental results show"
    ]
    
    text_lower = text.lower()
    matches = []
    for phrase in suspicious_phrases:
        if phrase in text_lower:
            matches.append(phrase)
    
    # Check for very long identical sentences (potential copy-paste)
    sentences = re.split(r'[.!?]+', text)
    long_sentences = [s.strip() for s in sentences if len(s.strip()) > 100]
    
    detected = len(matches) > 5 or len(long_sentences) > 10
    
    return {
        "detected": detected,
        "description": "Detects copy-paste from the web or other papers",
        "difficulty": "Easy (just rewrite it)",
        "details": f"Found {len(matches)} common phrases. {'High similarity detected.' if detected else 'No obvious copy-paste patterns found.'}"
    }


async def check_semantic_analysis(text: str, model: str = "grok-4-fast") -> Dict[str, Any]:
    """Check for heavy paraphrasing using semantic analysis"""
    try:
        ai_client = get_ai_client()
        
        prompt = f"""Analyze the following text for signs of heavy paraphrasing or unoriginal content. 
Look for:
1. Ideas that are presented without proper attribution
2. Concepts that appear to be heavily paraphrased from other sources
3. Lack of original analysis or synthesis

Text to analyze:
{text[:3000]}

Respond with JSON:
{{
    "is_paraphrased": true/false,
    "confidence": 0.0-1.0,
    "explanation": "brief explanation"
}}"""

        response = ai_client.chat.completions.create(
            model=model,
            messages=[
                {"role": "system", "content": "You are an expert at detecting paraphrased or unoriginal academic content. Always respond with valid JSON only."},
                {"role": "user", "content": prompt}
            ],
            temperature=0.3,
            max_tokens=300
        )
        
        result_text = response.choices[0].message.content.strip()
        if result_text.startswith("```"):
            result_text = result_text.split("```")[1]
            if result_text.startswith("json"):
                result_text = result_text[4:]
            result_text = result_text.strip()
        
        try:
            result = json.loads(result_text)
            detected = result.get("is_paraphrased", False) and result.get("confidence", 0) > 0.6
            return {
                "detected": detected,
                "description": "Detects heavy paraphrasing of ideas",
                "difficulty": "Hard (requires original logic)",
                "details": result.get("explanation", "Semantic analysis completed.")
            }
        except:
            return {
                "detected": False,
                "description": "Detects heavy paraphrasing of ideas",
                "difficulty": "Hard (requires original logic)",
                "details": "Analysis completed."
            }
    except Exception as e:
        return {
            "detected": False,
            "description": "Detects heavy paraphrasing of ideas",
            "difficulty": "Hard (requires original logic)",
            "details": f"Error in analysis: {str(e)}"
        }


